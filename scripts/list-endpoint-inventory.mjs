#!/usr/bin/env node
// ERP-995: inventory of collection GET routes and whether they follow the bounded read contract
// (BR-READ-001..003). Writes docs/api/list-endpoint-inventory.md; `--check` fails when it is stale.
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const apiSource = join(root, "apps/api/src");
const output = join(root, "docs/api/list-endpoint-inventory.md");

function controllers(directory, found = []) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) controllers(path, found);
    else if (entry.name.endsWith(".controller.ts")) found.push(path);
  }
  return found;
}

const rows = [];
for (const file of controllers(apiSource).sort()) {
  const source = readFileSync(file, "utf8");
  const base = /@Controller\("([^"]*)"\)/.exec(source)?.[1] ?? "";
  const bounded = /RawListQuery|parseListQuery|\blimit\b/.test(source);
  for (const match of source.matchAll(/@Get\((?:"([^"]*)")?\)/g)) {
    const sub = match[1] ?? "";
    if (sub && /[:*]/.test(sub)) continue; // single record routes
    if (sub && !/^[a-z-]+$/.test(sub)) continue;
    const route = `/${[base.replace(/^api\/v1\/organizations\/:organizationId\/?/, ""), sub].filter(Boolean).join("/")}`;
    const method = source.slice(match.index, match.index + 400);
    const pagedHere = /@Query\(\)\s*query/.test(method) || /@Query\("limit"\)/.test(method);
    rows.push({
      route,
      file: relative(root, file),
      status: pagedHere ? "bounded" : bounded ? "partial (file mentions limit)" : "unbounded",
    });
  }
}
rows.sort((a, b) => a.route.localeCompare(b.route));
const table = rows
  .map((r) => `| \`GET ${r.route || "/"}\` | ${r.status} | \`${r.file}\` |`)
  .join("\n");
const text = `# List endpoint inventory

Generated by \`node scripts/list-endpoint-inventory.mjs\` (do not edit by hand). Tracks BR-READ-001..003 progress for
ERP-996 and ERP-997. "bounded" = the route accepts the shared \`limit/cursor/view\` query and returns \`page\` metadata.
Anything else is either an unfinished route or a documented exception (single aggregate reports and capped lookups).

| Route | Status | Controller |
| --- | --- | --- |
${table}
`;
if (process.argv.includes("--check")) {
  if (!existsSync(output) || readFileSync(output, "utf8") !== text) {
    console.error(
      "docs/api/list-endpoint-inventory.md is stale; run node scripts/list-endpoint-inventory.mjs",
    );
    process.exit(1);
  }
  console.log("List endpoint inventory is current.");
} else {
  writeFileSync(output, text);
  console.log(`Wrote ${rows.length} routes.`);
}
